    /// <summary>
    ///     Applies the supported engines to the given dictionary of language
    ///     information.
    /// </summary>
    /// <param name="dictionary">The dictionary containing language information.</param>
    public static void ApplySupportTo(Dictionary<int, LanguageInfo> dictionary)
    {
        foreach (var pair in dictionary)
        {
            if (EngineMap.TryGetValue(pair.Value.Code, out var engines))
            {
                pair.Value.SupportedEngines = engines.ToList();
            }
        }
    }
